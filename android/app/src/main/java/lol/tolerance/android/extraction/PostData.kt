package lol.tolerance.android.extraction

import android.view.accessibility.AccessibilityNodeInfo
import lol.tolerance.android.scoring.ScoringSpec

/**
 * Platform-agnostic representation of a social media post extracted
 * from the accessibility node tree.
 */
data class PostData(
    val id: String,
    val platform: Platform,
    val author: String,
    val text: String,
    val score: Int?,        // likes/upvotes — null if not visible
    val numComments: Int,
    val subreddit: String?, // Reddit only
    // Screen position for overlay placement
    val screenBounds: ScreenBounds?,
    // Promoted post — never scored; covered only when ad blocking is on
    val isAd: Boolean = false,
    // On-screen post we couldn't identify (header off-screen, never seen whole).
    // No author/text, so key it by [id], not [contentHash].
    val isPartial: Boolean = false,
    // The user picked this (a creator they follow, their Following feed) rather than the
    // recommender pushing it — never covered, except as an ad
    val isChosen: Boolean = false,
    // A live stream (TikTok LIVE): nothing to score, covered only when the user hides LIVE
    val isLive: Boolean = false,
    // YouTube Shorts, the player or a shelf of them: covered only when the user hides Shorts.
    // isShortsPlayer is the full-screen player, which plays sound.
    val isShorts: Boolean = false,
    val isShortsPlayer: Boolean = false,
    // Labeled AI-generated by the app or the creator (unlabeled AI content isn't caught)
    val isAiLabeled: Boolean = false,
    val media: ScoringSpec.Media = ScoringSpec.Media.TEXT,
    // Video length ("15:25", "Short", "live stream"); the model weighs it as effort
    val length: String? = null,
    // Extra context for the model (sound, labels), not part of the post's identity
    val details: String? = null,
    // The post's on-screen container, for re-reading its position (scroll tracking).
    // Only meaningful from the extraction that produced it — don't cache.
    val node: AccessibilityNodeInfo? = null,
) {
    /** Content hash used for deduplication and cache lookup. */
    val contentHash: String by lazy {
        // details tells apart captionless videos from one creator; null keeps older hashes
        val raw = "${platform.name}:${author}:${text.take(200)}" + (details?.let { ":$it" } ?: "")
        raw.hashCode().toUInt().toString(16)
    }
}

data class ScreenBounds(
    val left: Int,
    val top: Int,
    val right: Int,
    val bottom: Int,
)

enum class Platform(vararg val packageNames: String) {
    TWITTER("com.twitter.android"),
    REDDIT("com.reddit.frontpage"),
    YOUTUBE("com.google.android.youtube"),
    INSTAGRAM("com.instagram.android"),
    // Global app; "trill" is the same app's package in some Asian markets
    TIKTOK("com.zhiliaoapp.musically", "com.ss.android.ugc.trill");

    companion object {
        fun fromPackage(pkg: String): Platform? =
            entries.find { pkg in it.packageNames }
    }
}
