import 'fake-indexeddb/auto';
import { describe, it, expect, vi, beforeAll, beforeEach } from 'vitest';
import type { EngagementScore } from '../src/shared/types';
import { AI_LABEL_PREFIX, SPONSORED_PREFIX } from '../src/shared/scoring-spec';

// Posts the site itself marks as sponsored or AI-generated get the top score in code,
// whatever the model returned.

const kv = new Map<string, unknown>();
beforeAll(() => {
  const listener = { addListener: vi.fn() };
  // A partial stand-in for the chrome global: the scorer pulls in the background script
  (globalThis as unknown as { chrome: unknown }).chrome = {
    runtime: { onInstalled: listener, onMessage: listener, onStartup: listener, getURL: vi.fn(), sendMessage: vi.fn(), setUninstallURL: vi.fn(), getManifest: () => ({ version: 'test' }), id: 'test' },
    storage: {
      local: {
        get: async (keys?: string | string[]) => {
          const wanted = keys === undefined ? [...kv.keys()] : typeof keys === 'string' ? [keys] : keys;
          return Object.fromEntries(wanted.filter(k => kv.has(k)).map(k => [k, structuredClone(kv.get(k))]));
        },
        set: async (items: Record<string, unknown>) => { for (const [k, v] of Object.entries(items)) kv.set(k, structuredClone(v)); },
      },
      onChanged: listener,
    },
    tabs: { onActivated: listener, onUpdated: listener, onRemoved: listener },
    alarms: { create: vi.fn(), onAlarm: listener },
    contextMenus: { create: vi.fn(), onClicked: listener, removeAll: vi.fn() },
  };
});

let applySiteLabels: typeof import('../src/background/scorer').applySiteLabels;
beforeAll(async () => {
  ({ applySiteLabels } = await import('../src/background/scorer'));
});
beforeEach(() => kv.clear());

const score = (postId: string, apiScore: number, over: Partial<EngagementScore> = {}): EngagementScore =>
  ({ postId, apiScore, bucket: 'low', factors: {}, timestamp: 1, apiReason: 'model reason', ...over });

describe('applySiteLabels', () => {
  it('gives a post the site marks as sponsored the top score, and says why', async () => {
    const scores = [score('ad', 10), score('plain', 30)];
    await applySiteLabels(scores, new Map([['ad', `${SPONSORED_PREFIX}Try our product`], ['plain', 'Just a post']]), 'reddit');
    expect(scores[0]).toMatchObject({ apiScore: 100, bucket: 'high' });
    expect(scores[0].apiReason).toBe('Marked as sponsored by the site. model reason');
    expect(scores[1]).toMatchObject({ apiScore: 30, bucket: 'low', apiReason: 'model reason' });
  });

  it('does the same for a post the site labels AI-generated', async () => {
    const scores = [score('ai', 40)];
    await applySiteLabels(scores, new Map([['ai', `${AI_LABEL_PREFIX}Sunset over the bay`]]), 'instagram');
    expect(scores[0].apiScore).toBe(100);
    expect(scores[0].apiReason).toContain('Labeled AI-generated by the site');
  });

  it('respects each setting being turned off', async () => {
    kv.set('settings', { penalizeFacebookAds: false, blurAiLabeled: false });
    const scores = [score('ad', 10), score('ai', 40)];
    await applySiteLabels(scores, new Map([['ad', `${SPONSORED_PREFIX}Buy`], ['ai', `${AI_LABEL_PREFIX}Art`]]), 'facebook');
    expect(scores.map(s => s.apiScore)).toEqual([10, 40]);

    kv.set('settings', { penalizeFacebookAds: false });   // AI setting back to its default, on
    await applySiteLabels(scores, new Map([['ad', `${SPONSORED_PREFIX}Buy`], ['ai', `${AI_LABEL_PREFIX}Art`]]), 'facebook');
    expect(scores.map(s => s.apiScore)).toEqual([10, 100]);
  });

  it('leaves failed scores to be scored again, and unmarked or unknown posts alone', async () => {
    const scores = [score('failed-ad', 50, { scoreFailed: true }), score('mention', 20), score('unknown', 20)];
    await applySiteLabels(scores, new Map([['failed-ad', `${SPONSORED_PREFIX}Buy`], ['mention', 'Why is everything [Sponsored] now']]), 'twitter');
    expect(scores.map(s => s.apiScore)).toEqual([50, 20, 20]);
    expect(scores[0].scoreFailed).toBe(true);
  });

  it('does not touch a marked post the model already scored at the top', async () => {
    const scores = [score('ad', 100, { bucket: 'high' })];
    await applySiteLabels(scores, new Map([['ad', `${SPONSORED_PREFIX}Buy`]]), 'reddit');
    expect(scores[0].apiReason).toBe('model reason');
  });
});
